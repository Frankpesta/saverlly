import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { Transform, Type } from 'class-transformer';
import {
  ArrayMaxSize,
  ArrayMinSize,
  ArrayUnique,
  IsArray,
  IsBoolean,
  IsDefined,
  IsIn,
  IsISO8601,
  IsNumber,
  IsOptional,
  IsString,
  Matches,
  MaxLength,
  Min,
  ValidateNested,
} from 'class-validator';
import {
  normalizeStoreSetupCode,
  STORE_SETUP_CHECK_KEYS,
  STORE_SETUP_CHECK_OUTCOMES,
  STORE_SETUP_CODE_PATTERN,
  type StoreSetupCheckKey,
  type StoreSetupCheckOutcome,
} from '@saverlly/shared-types';
import { CheckoutRecipeDto } from '../../merchants/dto/checkout-recipe.dto';

export class RedeemStoreSetupCodeDto {
  @ApiProperty({ example: 'SET-7K4Q-92MD' })
  @Transform(({ value }: { value: unknown }) =>
    typeof value === 'string' ? normalizeStoreSetupCode(value) : value,
  )
  @Matches(STORE_SETUP_CODE_PATTERN, {
    message: 'Enter the full setup code shown on the dashboard',
  })
  code: string;

  // Generated by the extension and kept across retries, so a redemption whose response was lost
  // can be repeated safely. Never placed in a URL.
  @ApiProperty({ description: '32 random bytes, base64url without padding' })
  @Matches(/^[A-Za-z0-9_-]{43}$/)
  token: string;
}

export class StoreSetupCheckDto {
  @ApiProperty({ enum: STORE_SETUP_CHECK_KEYS })
  @IsIn(STORE_SETUP_CHECK_KEYS)
  key: StoreSetupCheckKey;

  @ApiProperty({ enum: STORE_SETUP_CHECK_OUTCOMES })
  @IsIn(STORE_SETUP_CHECK_OUTCOMES)
  outcome: StoreSetupCheckOutcome;

  @ApiPropertyOptional({ maxLength: 300 })
  @IsOptional()
  @IsString()
  @MaxLength(300)
  detail?: string;
}

export class StoreSetupTestResultDto {
  @ApiProperty() @IsBoolean() passed: boolean;

  @ApiProperty({ type: [StoreSetupCheckDto] })
  @IsArray()
  @ArrayMinSize(1)
  @ArrayMaxSize(STORE_SETUP_CHECK_KEYS.length)
  @ArrayUnique((check: StoreSetupCheckDto) => check?.key, {
    message: 'Each check key may appear only once',
  })
  @ValidateNested({ each: true })
  @Type(() => StoreSetupCheckDto)
  checks: StoreSetupCheckDto[];

  @ApiPropertyOptional()
  @IsOptional()
  @IsNumber({ allowNaN: false, allowInfinity: false, maxDecimalPlaces: 2 })
  @Min(0)
  cartTotal?: number;

  @ApiProperty() @IsISO8601({ strict: true }) testedAt: string;
}

// @IsDefined on both: @ValidateNested alone silently accepts a missing nested object.
export class SubmitStoreSetupRecipeDto {
  @ApiProperty({ type: CheckoutRecipeDto })
  @IsDefined()
  @ValidateNested()
  @Type(() => CheckoutRecipeDto)
  recipe: CheckoutRecipeDto;

  @ApiProperty({ type: StoreSetupTestResultDto })
  @IsDefined()
  @ValidateNested()
  @Type(() => StoreSetupTestResultDto)
  testResult: StoreSetupTestResultDto;
}
